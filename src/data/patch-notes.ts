/** Keeps every release note short and consistent in the in-app archive. */
function note(
  version: string,
  releasedAt: string,
  title: string,
  summary: string,
  ...items: string[]
): PatchNoteRelease {
  return {
    version,
    releasedAt,
    title,
    summary,
    sections: [{ title: "Highlights", items }],
  }
}

